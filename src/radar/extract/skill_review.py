"""Offline upkeep of the skill dictionary v1 and its numbers.

    python -m radar.extract.skill_review candidates   # train_pool: frequent unknown spellings, entry counts
    (WSL) python -m radar.extract.skill_embed --model <name>   # once per model
    python -m radar.extract.skill_review select       # which embedding proposes aliases best
    python -m radar.extract.skill_review propose      # neighbours and clusters of unknown spellings
    python -m radar.extract.skill_review provenance --write   # [provenance] block of configs/skills.toml
    python -m radar.extract.skill_review report       # results/skills/normalization.json

Candidates come from train_pool only: the items of Habr's "Навыки" header, and Latin words and word
pairs in Russian texts (a Latin word in a Russian vacancy is most often a product name). A spelling
seen in fewer than `floor` records is not proposed. Proposals go to `data/skills/proposals.jsonl` for a
person to read; nothing is added to the dictionary by this code.

`select` scores each embedding (and a character n-gram baseline) on the dictionary's own aliases:
for every alias that differs from its canonical name beyond case and separators, is the nearest
other spelling one of the same skill? The threshold is the lowest cosine at which the nearest
neighbour is right in at least `min_precision` of the aliases above it; it decides what is shown as
an alias proposal, not what is accepted.
"""

