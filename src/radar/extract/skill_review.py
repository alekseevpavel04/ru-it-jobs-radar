Vectors = npt.NDArray[np.float32]

SKILLS_DATA = ROOT / "data" / "skills"
PROVENANCE_MARKER = "# --- generated by `python -m radar.extract.skill_review provenance --write`"
CHAR_MODEL = "char-ngrams"
_TOKEN = re.compile(r"(?<![a-z0-9+#])[a-z][a-z0-9+#]*(?:[.\-/][a-z0-9+#]+)*")


@dataclass(frozen=True)
class Settings:
    floor: int
    model: str
    threshold: float
    min_precision: float


def settings(path: Path = sk.DICTIONARY) -> Settings:
    r = tomllib.loads(path.read_text(encoding="utf-8"))["review"]
    return Settings(int(r["floor"]), str(r["model"]), float(r["threshold"]), float(r["min_precision"]))


def pool_records() -> list[tuple[str, str]]:
    corpus = data_dir() / "corpus"
    split = pq.read_table(corpus / "split.parquet", columns=["split", "member_ids"]).to_pylist()
    pool = {rid for row in split if row["split"] == "train_pool" for rid in row["member_ids"]}
    rows = pq.read_table(corpus / "corpus.parquet", columns=["id", "input"]).to_pylist()
    return sorted((r["id"], r["input"]) for r in rows if r["id"] in pool)


def text_candidates(text: str) -> set[str]:
    """Habr header items, and Latin words and word pairs of a Russian text, lowercased."""
    inp = baseline.split_input(text)
    found = {sk.clean(item) for item in inp.header.get("Навыки", "").split(",") if item.strip()}
    if baseline.predict_lang(inp) != "ru":
        return found
    norm = baseline.normalize(inp.body)
    tokens = list(_TOKEN.finditer(norm))
    found.update(m.group(0) for m in tokens)
    for a, b in pairwise(tokens):
        if norm[a.end() : b.start()] == " ":
            found.add(f"{a.group(0)} {b.group(0)}")
    return found


def dictionary_spellings(d: sk.Dictionary) -> list[tuple[str, str]]:
    """(spelling, canonical) for every name and alias, one per distinct lookup key."""
    seen: set[str] = set()
    out = []
    for skill in d.skills.values():
        for spelling in (skill.name, *skill.aliases):
            if sk.key(spelling) not in seen:
                seen.add(sk.key(spelling))
                out.append((spelling, skill.name))
    return out


def cmd_candidates(cfg: Settings) -> int:
    d = sk.load()
    records = pool_records()
    matcher = sd.build(d, search_gold_only=True)
    docs: Counter[str] = Counter()
    entry_docs: Counter[str] = Counter()
    for i, (_, text) in enumerate(records, start=1):
        docs.update(text_candidates(text))
        source, english = skill_source(text)
        entry_docs.update(sd.find_skills(source, baseline.normalize(source), english, matcher))
        if i % 2000 == 0:
            log.info("%d/%d records", i, len(records))
    rows = []
    for spelling, n in docs.most_common():
        if n < cfg.floor:
            break
        r = sk.resolve(spelling, d)
        rejected = sk.key(spelling) in d.rejected
        rows.append(
            {"spelling": spelling, "docs": n, "status": r.status, "canonical": r.canonical, "rejected": rejected}
        )
    SKILLS_DATA.mkdir(parents=True, exist_ok=True)
    with (SKILLS_DATA / "candidates.jsonl").open("w", encoding="utf-8", newline="\n") as f:
        f.writelines(json.dumps(r, ensure_ascii=False) + "\n" for r in rows)
    (SKILLS_DATA / "pool_counts.json").write_text(
        json.dumps({"records": len(records), "counts": dict(entry_docs.most_common())}, ensure_ascii=False, indent=1),
        encoding="utf-8",
    )
    unknown = [str(r["spelling"]) for r in rows if r["status"] == "unknown" and not r["rejected"]]
    strings = sorted({s for s, _ in dictionary_spellings(d)} | set(unknown))
    digest = hashlib.sha256("\n".join(strings).encode("utf-8")).hexdigest()
    (SKILLS_DATA / "strings.json").write_text(
        json.dumps({"sha256": digest, "strings": strings}, ensure_ascii=False), encoding="utf-8"
    )
    by_status = Counter(r["status"] for r in rows)
    print(f"train_pool records {len(records)}; spellings in {cfg.floor}+ records: {len(rows)} {dict(by_status)}")
    print(f"unknown and not yet rejected: {len(unknown)}; strings to embed: {len(strings)}")
    return 0


# --- embeddings ----------------------------------------------------------------------------------


def char_vectors(strings: Sequence[str], dim: int = 4096) -> Vectors:
    """Hashed TF-IDF of character 2-4-grams: the no-model baseline."""
    grams = []
    for s in strings:
        padded = f" {sk.clean(s)} "
        grams.append(Counter(padded[i : i + n] for n in (2, 3, 4) for i in range(len(padded) - n + 1)))
    df: Counter[str] = Counter(g for c in grams for g in c)
    out = np.zeros((len(strings), dim), dtype=np.float32)
    for row, c in enumerate(grams):
        for g, tf in c.items():
            out[row, zlib.crc32(g.encode("utf-8")) % dim] += tf * np.log(len(strings) / df[g])
    norms = np.linalg.norm(out, axis=1, keepdims=True)
    unit: Vectors = (out / np.where(norms > 0, norms, 1)).astype(np.float32)
    return unit


def load_vectors(model: str) -> tuple[list[str], Vectors]:
    doc = json.loads((SKILLS_DATA / "strings.json").read_text(encoding="utf-8"))
    strings: list[str] = doc["strings"]
    if model == CHAR_MODEL:
        return strings, char_vectors(strings)
    path = SKILLS_DATA / "emb" / f"{model.replace('/', '__')}.npy"
    meta = json.loads(path.with_suffix(".json").read_text(encoding="utf-8"))
    if meta["strings_sha256"] != doc["sha256"]:
        raise ValueError(f"{path} was embedded from other strings; run skill_embed again")
    return strings, np.load(path).astype(np.float32)


def available_models() -> list[str]:
    emb = sorted((SKILLS_DATA / "emb").glob("*.npy"))
    return [CHAR_MODEL, *(p.stem.replace("__", "/") for p in emb)]


def alias_retrieval(d: sk.Dictionary, strings: list[str], vectors: Vectors, min_precision: float) -> dict[str, Any]:
    index = {s: i for i, s in enumerate(strings)}
    pairs = [p for p in dictionary_spellings(d) if p[0] in index]
    spell_idx = np.array([index[s] for s, _ in pairs])
    owners = [c for _, c in pairs]
    queries = [(i, s, c) for i, (s, c) in enumerate(pairs) if s != c and sk.key(s) != sk.key(c)]
    sims = vectors[spell_idx[[q[0] for q in queries]]] @ vectors[spell_idx].T
    for row, (i, _, _) in enumerate(queries):
        sims[row, i] = -np.inf  # leave the alias itself out
    best = sims.argmax(axis=1)
    cos = sims[np.arange(len(queries)), best]
    right = np.array([owners[b] == c for b, (_, _, c) in zip(best, queries, strict=True)])
    order = np.argsort(-cos)
    threshold, above = float("inf"), 0
    for k in range(1, len(order) + 1):
        if right[order[:k]].mean() >= min_precision:
            threshold, above = float(cos[order[k - 1]]), k
    return {
        "queries": len(queries),
        "top1_right": int(right.sum()),
        "threshold": threshold,
        "above_threshold": above,
        "right_above_threshold": int(right[order[:above]].sum()) if above else 0,
    }


def cmd_select(cfg: Settings) -> int:
    d = sk.load()
    metrics: dict[str, dict[str, Any]] = {}
    for model in available_models():
        strings, vectors = load_vectors(model)
        r = alias_retrieval(d, strings, vectors, cfg.min_precision)
        name = model.replace("/", "__")
        metrics[f"{name}_top1"] = {
            "value": round(r["top1_right"] / r["queries"], 4),
            "n": r["top1_right"],
            "denominator": r["queries"],
        }
        metrics[f"{name}_threshold"] = {"value": round(r["threshold"], 4)}
        metrics[f"{name}_aliases_above_threshold"] = {
            "value": round(r["above_threshold"] / r["queries"], 4),
            "n": r["above_threshold"],
            "denominator": r["queries"],
        }
        right, queries, above = r["top1_right"], r["queries"], r["above_threshold"]
        print(f"{model:36} top1 {right}/{queries}  threshold {r['threshold']:.3f}  above {above}")
    path = write_result(
        "skills/proposal_models.json",
        metrics,
        source_script="src/radar/extract/skill_review.py",
        method="nearest other spelling of the dictionary for each non-trivial alias; "
        "right if it belongs to the same skill",
        min_precision=cfg.min_precision,
        dictionary_sha256=sha256(sk.DICTIONARY),
    )
    print(path)
    return 0


# --- proposals -----------------------------------------------------------------------------------


def _components(n: int, edges: list[tuple[int, int]]) -> list[int]:
    parent = list(range(n))

    def find(x: int) -> int:
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for a, b in edges:
        parent[find(a)] = find(b)
    return [find(i) for i in range(n)]


def cmd_propose(cfg: Settings) -> int:
    d = sk.load()
    strings, vectors = load_vectors(cfg.model)
    index = {s: i for i, s in enumerate(strings)}
    rows = [json.loads(x) for x in (SKILLS_DATA / "candidates.jsonl").read_text(encoding="utf-8").splitlines()]
    unknown = [r for r in rows if r["status"] == "unknown" and not r["rejected"] and r["spelling"] in index]
    pairs = [p for p in dictionary_spellings(d) if p[0] in index]
    uvec = vectors[[index[r["spelling"]] for r in unknown]]
    to_dict = uvec @ vectors[[index[s] for s, _ in pairs]].T
    among = uvec @ uvec.T
    edges = [(int(a), int(b)) for a, b in zip(*np.nonzero(np.triu(among >= cfg.threshold, k=1)), strict=True)]
    comp = _components(len(unknown), edges)
    members: dict[int, list[int]] = defaultdict(list)
    for i, c in enumerate(comp):
        members[c].append(i)
    out = []
    for i, r in enumerate(unknown):
        j = int(to_dict[i].argmax())
        cos = float(to_dict[i, j])
        group = sorted(members[comp[i]], key=lambda m: -unknown[m]["docs"])
        if cos >= cfg.threshold:
            proposal = f"alias of {pairs[j][1]}"
        elif len(group) > 1:
            proposal = f"cluster around {unknown[group[0]]['spelling']}"
        else:
            proposal = "new entry or reject"
        out.append(
            {
                "spelling": r["spelling"],
                "docs": r["docs"],
                "nearest": pairs[j][1],
                "nearest_spelling": pairs[j][0],
                "cosine": round(cos, 4),
                "proposal": proposal,
                "cluster": [unknown[m]["spelling"] for m in group[:8]],
            }
        )
    with (SKILLS_DATA / "proposals.jsonl").open("w", encoding="utf-8", newline="\n") as f:
        f.writelines(json.dumps(r, ensure_ascii=False) + "\n" for r in out)
    kinds = Counter(r["proposal"].split(" ")[0] for r in out)
    print(f"{len(out)} unknown spellings in {cfg.floor}+ records, model {cfg.model}, threshold {cfg.threshold}")
    print(dict(kinds))
    print(SKILLS_DATA / "proposals.jsonl")
    return 0


# --- provenance ----------------------------------------------------------------------------------


def gold_names(split: str) -> set[str]:
    """Skill names of a gold split, nothing else of it: the vocabulary of spellings."""
    names: set[str] = set()
    for line in (data_dir() / "gold" / f"{split}.jsonl").read_text(encoding="utf-8").splitlines():
        if line.strip():
            names.update(json.loads(line)["fields"]["skills"])
    return names


def v0_vocabulary(d: sk.Dictionary) -> set[str]:
    """Entries the v0 baseline already searched: some spelling matches a v0 synonym in full."""
    synonyms = [re.compile(s) for row in sd.v0_rows() for s in row["synonyms"].split("|")]
    return {
        skill.name
        for skill in d.skills.values()
        if any(p.fullmatch(sk.clean(s)) for s in (skill.name, *skill.aliases) for p in synonyms)
    }


def provenance(d: sk.Dictionary, floor: int) -> dict[str, str]:
    counts: dict[str, int] = json.loads((SKILLS_DATA / "pool_counts.json").read_text(encoding="utf-8"))["counts"]
    v0 = v0_vocabulary(d)
    origin: dict[str, set[str]] = defaultdict(set)
    for split in ("dev", "test"):
        for name in gold_names(split):
            canonical = sk.resolve(name, d).canonical
            if canonical is not None:
                origin[canonical].add(split)
    return {
        name: "+".join(sorted(splits))
        for name, splits in sorted(origin.items(), key=lambda kv: kv[0].casefold())
        if name not in v0 and counts.get(name, 0) < floor
    }


def cmd_provenance(cfg: Settings, write: bool) -> int:
    d = sk.load()
    gold_only = provenance(d, cfg.floor)
    records = json.loads((SKILLS_DATA / "pool_counts.json").read_text(encoding="utf-8"))["records"]
    split_counts = Counter(gold_only.values())
    print(f"gold-only entries: {len(gold_only)} of {len(d.skills)} {dict(split_counts)}")
    if not write:
        return 0
    text = sk.DICTIONARY.read_text(encoding="utf-8")
    head = text.split(PROVENANCE_MARKER)[0].rstrip("\n")
    lines = [
        PROVENANCE_MARKER + ", do not edit by hand ---",
        "# Entries whose only evidence is the gold labels: a name of the dev or test labels that the v0",
        f"# dictionary did not search and that the v1 search finds in fewer than {cfg.floor} of the {records}",
        "# train_pool records counted by `candidates`.",
        "# The baseline does not search them; the value says which split's labels named the entry.",
        "[provenance.gold_only]",
        *(f"{json.dumps(name, ensure_ascii=False)} = {json.dumps(split)}" for name, split in gold_only.items()),
    ]
    sk.DICTIONARY.write_text(head + "\n\n" + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    sk.load.cache_clear()
    sk.load()
    print(f"written to {sk.DICTIONARY}")
    return 0


# --- report --------------------------------------------------------------------------------------


def skill_source(text: str) -> tuple[str, bool]:
    """The text the baseline searches for skills, and whether it is English (as in baseline.extract)."""
    inp = baseline.split_input(text)
    title = inp.title
    if title is None and inp.body:
        title = inp.body.split("\n", 1)[0]
    return "\n".join(filter(None, (title, inp.header.get("Навыки"), inp.body))), baseline.predict_lang(inp) == "en"


def coverage(mentions: list[str], d: sk.Dictionary) -> dict[str, Any]:
    statuses: Counter[str] = Counter()
    merged: Counter[str] = Counter()
    unknown: Counter[str] = Counter()
    for m in mentions:
        r = sk.resolve(m, d)
        statuses[r.status] += 1
        if r.canonical is not None and normalize_item(r.canonical) != normalize_item(m):
            merged[f"{m} -> {r.canonical}"] += 1
        if r.status == "unknown":
            unknown[m] += 1
    return {"statuses": statuses, "merged": merged, "unknown": unknown}


def v0_coverage(mentions: list[str]) -> tuple[int, int]:
    """Mentions a v0 synonym matches in full, and of those, mapped to their own name."""
    rows = [(r["skill"], re.compile("|".join(f"(?:{s})" for s in r["synonyms"].split("|")))) for r in sd.v0_rows()]
    mapped = same = 0
    for m in mentions:
        c = sk.clean(m)
        hit = next((name for name, p in rows if p.fullmatch(c)), None)
        if hit is not None:
            mapped += 1
            same += normalize_item(hit) == normalize_item(m)
    return mapped, same


def share(n: int, total: int) -> dict[str, Any]:
    return {"value": round(n / total, 4), "n": n, "denominator": total}


def strict_vocabulary(d: sk.Dictionary) -> set[str]:
    """Entries a dictionary built without any gold names would search: those v0 searched, and those
    with a spelling that the train_pool candidate extraction found in `floor`+ records by itself."""
    found = {
        sk.key(json.loads(x)["spelling"])
        for x in (SKILLS_DATA / "candidates.jsonl").read_text(encoding="utf-8").splitlines()
    }
    from_pool = {s.name for s in d.skills.values() if any(sk.key(a) in found for a in (s.name, *s.aliases))}
    return v0_vocabulary(d) | from_pool


def review_metrics(d: sk.Dictionary) -> dict[str, dict[str, Any]]:
    """How the train_pool review went: candidates by their status now, and how many embedding alias
    proposals of the last `propose` run became an alias of the proposed skill."""
    candidates = [json.loads(x) for x in (SKILLS_DATA / "candidates.jsonl").read_text(encoding="utf-8").splitlines()]
    proposals = [json.loads(x) for x in (SKILLS_DATA / "proposals.jsonl").read_text(encoding="utf-8").splitlines()]
    status = Counter("rejected" if c["rejected"] else str(c["status"]) for c in candidates)
    aliases = [p for p in proposals if p["proposal"].startswith("alias of ")]
    accepted = sum(sk.resolve(p["spelling"], d).canonical == p["proposal"].removeprefix("alias of ") for p in aliases)
    reviewed = len(proposals)
    resolved = sum(sk.resolve(p["spelling"], d).status != "unknown" for p in proposals)
    return {
        "pool_candidates": {"value": len(candidates)},
        "pool_candidates_resolved": share(status["known"] + status["rule"], len(candidates)),
        "pool_candidates_non_skill": share(status["non_skill"], len(candidates)),
        "pool_candidates_rejected": share(status["rejected"], len(candidates)),
        "pool_candidates_unreviewed": share(status["unknown"], len(candidates)),
        "proposals_resolved_after_review": share(resolved, reviewed),
        "alias_proposals_accepted": share(accepted, len(aliases)),
    }


def cmd_report() -> int:
    cfg = load_config()
    d = sk.load()
    gold_path = data_dir() / "gold" / "dev.jsonl"
    inputs_path = data_dir() / "gold" / "dev_inputs.jsonl"
    gold = load_gold(gold_path)
    texts = {
        json.loads(x)["id"]: json.loads(x)["input"]
        for x in inputs_path.read_text(encoding="utf-8").splitlines()
        if x.strip()
    }
    mentions = [s for g in gold for s in g.fields.skills]
    total = len(mentions)
    dev_only = [n for n, split in d.gold_only.items() if split == "dev"]
    full = coverage(mentions, d)
    held = coverage(mentions, d.without(dev_only))
    v0_mapped, v0_same = v0_coverage(mentions)

    base = [baseline.extract(texts[g.id]) for g in gold]
    sources = [skill_source(texts[g.id]) for g in gold]
    v1_all = sd.build(d, search_gold_only=True)
    strict_names = strict_vocabulary(d)
    v1_strict = sd.build(d.without(set(d.skills) - strict_names))

    def with_skills(matcher: sd.Matcher) -> list[VacancyFields | None]:
        return [
            f.model_copy(update={"skills": sd.find_skills(src, baseline.normalize(src), en, matcher)[:60]})
            for f, (src, en) in zip(base, sources, strict=True)
        ]

    systems = {
        "v0_casefold": (with_skills(sd.load_v0()), normalize_item),
        "v0_dictionary": (with_skills(sd.load_v0()), sk.eval_key),
        "v1_casefold": (with_skills(sd.load()), normalize_item),
        "v1_dictionary": (with_skills(sd.load()), sk.eval_key),
        "v1_strict_dictionary": (with_skills(v1_strict), sk.eval_key),
        "v1_gold_vocabulary_dictionary": (with_skills(v1_all), sk.eval_key),
    }
    fields = [g.fields for g in gold]
    weights = resample_weights(len(gold), cfg.n_resamples, cfg.seed)
    stats: dict[str, dict[str, Stat]] = {
        name: score(fields, preds, cfg.salary_rel_tol, cfg.macro_fields, normalize_skill=norm)
        for name, (preds, norm) in systems.items()
    }
    keep = ("skills_f1", "skills_precision", "skills_recall", "macro_f1")
    metrics: dict[str, dict[str, Any]] = {
        "dictionary_skills": {"value": len(d.skills)},
        "dictionary_aliases": {"value": sum(len(s.aliases) for s in d.skills.values())},
        "dictionary_patterns": {"value": sum(len(s.patterns) for s in d.skills.values())},
        "dictionary_non_skill_names": {"value": len(d.non_skill_keys)},
        "dictionary_gold_only": share(len(d.gold_only), len(d.skills)),
        "dictionary_strict_vocabulary": share(len(strict_names), len(d.skills)),
        "dev_mentions": {"value": total},
        "dev_coverage_v1": share(full["statuses"]["known"] + full["statuses"]["rule"], total),
        "dev_coverage_v1_without_dev_only_entries": share(held["statuses"]["known"] + held["statuses"]["rule"], total),
        "dev_unknown_v1_without_dev_only_entries": share(held["statuses"]["unknown"], total),
        "dev_non_skill_v1": share(full["statuses"]["non_skill"], total),
        "dev_merged_spellings_v1": share(sum(full["merged"].values()), total),
        "dev_coverage_v0": share(v0_mapped, total),
        "dev_coverage_v0_own_name": share(v0_same, total),
        **review_metrics(d),
    }
    for name, st in stats.items():
        intervals = bootstrap({k: st[k] for k in keep}, weights, cfg.confidence)
        for k in keep:
            iv = intervals[k]
            if iv is not None:
                metrics[f"{name}_{k}"] = {
                    "value": round(iv.value, 6),
                    "ci_low": round(iv.low, 6),
                    "ci_high": round(iv.high, 6),
                }
    differences = {
        "dictionary_v1_minus_v0_casefold": ("v1_casefold", "v0_casefold"),
        "dictionary_v1_minus_v0_dictionary": ("v1_dictionary", "v0_dictionary"),
        "comparison_dictionary_minus_casefold_v0": ("v0_dictionary", "v0_casefold"),
        "comparison_dictionary_minus_casefold_v1": ("v1_dictionary", "v1_casefold"),
        "strict_minus_v0_dictionary": ("v1_strict_dictionary", "v0_dictionary"),
        "v1_minus_strict_dictionary": ("v1_dictionary", "v1_strict_dictionary"),
        "gold_vocabulary_minus_v1_dictionary": ("v1_gold_vocabulary_dictionary", "v1_dictionary"),
    }
    for label, (a, b) in differences.items():
        diff = paired_bootstrap(
            {"skills_f1": stats[a]["skills_f1"]}, {"skills_f1": stats[b]["skills_f1"]}, weights, cfg.confidence
        )
        iv = diff["skills_f1"]
        if iv is not None:
            metrics[f"{label}_skills_f1"] = {
                "value": round(iv.value, 6),
                "ci_low": round(iv.low, 6),
                "ci_high": round(iv.high, 6),
            }

    path = write_result(
        "skills/normalization.json",
        metrics,
        source_script="src/radar/extract/skill_review.py",
        split="dev",
        gold_file="data/gold/dev.jsonl",
        gold_sha256=sha256(gold_path),
        dictionary_sha256=sha256(sk.DICTIONARY),
        n_examples=len(gold),
        bootstrap={"n_resamples": cfg.n_resamples, "seed": cfg.seed, "confidence": cfg.confidence},
        systems={
            "v0_casefold": "baseline skills by the v0 seed, names compared by case and whitespace (E1)",
            "v0_dictionary": "baseline skills by the v0 seed, names compared after v1 normalization",
            "v1_casefold": "baseline skills by v1 without gold-only entries, compared by case and whitespace",
            "v1_dictionary": "baseline skills by v1 without gold-only entries, compared after v1 normalization",
            "v1_strict_dictionary": "v1 searching only entries v0 searched or whose spelling train_pool candidates "
            "surfaced on their own, compared after v1 normalization",
            "v1_gold_vocabulary_dictionary": "v1 searching gold-only entries too: leaks label names, a reference only",
        },
        categories=dict(Counter(s.category for s in d.skills.values()).most_common()),
        gold_only_by_split=dict(Counter(d.gold_only.values())),
        dev_unknown_without_dev_only_entries=dict(held["unknown"].most_common()),
        dev_merged_spellings=dict(full["merged"].most_common()),
    )
    for k, v in metrics.items():
        extra = f" {v['n']}/{v['denominator']}" if "denominator" in v else ""
        ci = f" [{v['ci_low']:.3f}, {v['ci_high']:.3f}]" if "ci_low" in v else ""
        print(f"{k:58} {v['value']}{extra}{ci}")
    print(path)
    return 0


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    ap = argparse.ArgumentParser(prog="python -m radar.extract.skill_review", description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("candidates", "select", "propose", "report"):
        sub.add_parser(name)
    prov = sub.add_parser("provenance")
    prov.add_argument("--write", action="store_true", help="rewrite the [provenance] block of configs/skills.toml")
    args = ap.parse_args(argv)
    if args.cmd == "report":
        return cmd_report()
    cfg = settings()
    if args.cmd == "candidates":
        return cmd_candidates(cfg)
    if args.cmd == "select":
        return cmd_select(cfg)
    if args.cmd == "propose":
        return cmd_propose(cfg)
    return cmd_provenance(cfg, args.write)


if __name__ == "__main__":
    sys.exit(main())
